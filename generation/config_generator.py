"""
Configuration Generator Module
Converts decomposed steps and SLM outputs into formalized, vendor-specific
device configuration blocks. Handles multi-device configurations separated by '~~~'.
"""

import os
import sys
from typing import Dict, Any, List, Optional

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from models.slm_engine import SLMEngine
from knowledge_base.kb_manager import KnowledgeBaseManager


class ConfigurationGenerator:
    """Orchestrates configuration generation from requirements and decomposed subtasks."""

    def __init__(self, slm_engine: Optional[SLMEngine] = None, kb_manager: Optional[KnowledgeBaseManager] = None):
        self.slm = slm_engine or SLMEngine()
        self.kb = kb_manager or KnowledgeBaseManager()

    def generate(
        self,
        requirement_text: str,
        category: str,
        steps: List[str],
        extracted_entities: Dict[str, Any],
        device_name: str = "Switch1"
    ) -> Dict[str, Any]:
        """
        Generate formalized device configuration.
        """
        raw_cli = self.slm.generate_configuration_cli(
            requirement_text=requirement_text,
            category=category,
            steps=steps,
            extracted_entities=extracted_entities
        )

        # Split multi-device blocks if delimited by '~~~'
        device_blocks = {}
        if "~~~" in raw_cli:
            parts = [p.strip() for p in raw_cli.split("~~~") if p.strip()]
            for idx, part in enumerate(parts, 1):
                dev_label = f"Device_{idx}"
                device_blocks[dev_label] = self._format_cli_block(part, dev_label)
        else:
            device_blocks[device_name] = self._format_cli_block(raw_cli, device_name)

        primary_cli = device_blocks[device_name] if device_name in device_blocks else list(device_blocks.values())[0]

        return {
            "device_name": device_name,
            "category": category,
            "raw_cli": raw_cli,
            "formatted_cli": primary_cli,
            "all_device_blocks": device_blocks,
            "line_count": len([l for l in primary_cli.splitlines() if l.strip()])
        }

    def _format_cli_block(self, cli_text: str, hostname: str) -> str:
        """Add standard Cisco IOS configuration headers and trailers."""
        header = f"! Generated by SLM-NetConfig for {hostname}\n! Cisco IOS XE Software\nhostname {hostname}\n!"
        trailer = "\n!\nend\nwrite memory"
        cleaned_body = "\n".join([line for line in cli_text.splitlines() if not line.strip().startswith("hostname")])
        return f"{header}\n{cleaned_body}{trailer}"


